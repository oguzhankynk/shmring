#!/usr/bin/env bash
# Builds the benchmark tools in release mode, runs them, and writes docs/BENCHMARKS.md.
#
# Usage: scripts/bench.sh [--render]
#   --render   do not measure again; rebuild docs/BENCHMARKS.md from the saved raw results of the
#              last run (build/bench/results/)
#
# Environment overrides:
#   BENCH_CPU_A, BENCH_CPU_B   CPUs to pin the two sides to (default 0 and 2)
#   BENCH_ITERATIONS           ping-pong samples per repetition (default 200000)
#   BENCH_REPETITIONS          repetitions for transports that sleep in the kernel
#                              (ping-pong 5, throughput 3)
#   BENCH_FAST_REPETITIONS     repetitions for transports that spin (ping-pong 21, throughput 9)
#   BENCH_MESSAGES             messages per throughput run (default depends on payload size)
#   BENCH_FILTER               run only transports whose name contains this text
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD="${ROOT}/build/bench"
OUT="${ROOT}/docs/BENCHMARKS.md"
export BENCH_CPU_A="${BENCH_CPU_A:-0}"
export BENCH_CPU_B="${BENCH_CPU_B:-2}"

RESULTS="${BUILD}/results"
MODE="${1:-run}"

cmake -S "${ROOT}" -B "${BUILD}" -G Ninja -DCMAKE_BUILD_TYPE=Release \
  -DSHMRING_BUILD_BENCHMARKS=ON -DSHMRING_BUILD_TESTS=OFF -DSHMRING_BUILD_DOCS=OFF \
  -DSHMRING_BUILD_EXAMPLES=OFF >/dev/null
cmake --build "${BUILD}"

cache_value() { sed -n "s/^$1:[A-Z]*=//p" "${BUILD}/CMakeCache.txt" | head -n 1; }
CXX_BIN="$(cache_value CMAKE_CXX_COMPILER)"
CXX_VERSION="$("${CXX_BIN}" --version | head -n 1)"
CXX_FLAGS="$(cache_value CMAKE_CXX_FLAGS) $(cache_value CMAKE_CXX_FLAGS_RELEASE)"
CPU_MODEL="$(lscpu | sed -n 's/^Model name:[[:space:]]*//p')"
CPU_COUNT="$(nproc)"
KERNEL="$(uname -r)"
GOVERNOR="not exposed (no cpufreq in this environment)"
if [[ -r /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor ]]; then
  GOVERNOR="$(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor)"
fi
VIRT="bare metal or unknown"
if grep -qi microsoft /proc/version 2>/dev/null; then
  VIRT="WSL2 (virtualized CPUs; the guest cannot control which host core a vCPU runs on)"
fi
COMMIT="$(git -C "${ROOT}" rev-parse --short HEAD 2>/dev/null || echo unknown)"
TOPOLOGY="$(lscpu -p=CPU,CORE | grep -v '^#' | awk -F, '{a[$2]=a[$2] (a[$2]?",":"") $1} END{for (c in a) printf "core %s: cpu %s; ", c, a[c]}')"

TASKSET=()
if command -v taskset >/dev/null; then
  TASKSET=(taskset -c "${BENCH_CPU_A},${BENCH_CPU_B}")
fi

mkdir -p "${RESULTS}"
if [[ "${MODE}" != "--render" ]]; then
  echo "== ping-pong latency"
  "${BUILD}/bench/shmring_pingpong" | tee "${RESULTS}/pingpong.txt"
  echo "== throughput"
  "${BUILD}/bench/shmring_throughput" | tee "${RESULTS}/throughput.txt"
  echo "== run-to-run variation"
  : > "${RESULTS}/variation.txt"
  for _ in $(seq 1 16); do
    BENCH_FILTER="shmring spsc_ring (busy" BENCH_ITERATIONS=100000 BENCH_REPETITIONS=1 \
      BENCH_FAST_REPETITIONS=1 "${BUILD}/bench/shmring_pingpong" |
      awk -F'|' '/processes/ { gsub(/ /, "", $4); printf "%s ", $4; exit }' >> "${RESULTS}/variation.txt"
  done
  cat "${RESULTS}/variation.txt"; echo
  echo "== google benchmark"
  "${TASKSET[@]}" "${BUILD}/bench/shmring_micro" --benchmark_repetitions=5 \
    --benchmark_report_aggregates_only=true --benchmark_min_time=0.5s 2>&1 | tee "${RESULTS}/micro.txt"
fi
PINGPONG="$(cat "${RESULTS}/pingpong.txt")"
THROUGHPUT="$(cat "${RESULTS}/throughput.txt")"
MICRO="$(cat "${RESULTS}/micro.txt")"
VARIATION="$(cat "${RESULTS}/variation.txt")"

{
  echo "# Benchmarks"
  echo
  echo "Generated by \`scripts/bench.sh\` on $(date -u +%Y-%m-%d) from commit \`${COMMIT}\`. Every number"
  echo "below was measured on the machine described here; nothing is copied from elsewhere."
  echo
  echo "## Environment"
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| CPU | ${CPU_MODEL} (${CPU_COUNT} logical CPUs) |"
  echo "| Virtualization | ${VIRT} |"
  echo "| Kernel | ${KERNEL} |"
  echo "| Compiler | ${CXX_VERSION} |"
  echo "| Flags | CMAKE_BUILD_TYPE=Release, \`${CXX_FLAGS}\` |"
  echo "| Frequency governor | ${GOVERNOR} |"
  echo "| Core pinning | the two sides are pinned to CPU ${BENCH_CPU_A} and CPU ${BENCH_CPU_B} with \`sched_setaffinity\` |"
  echo "| CPU topology reported by the guest | ${TOPOLOGY} |"
  echo "| Cache line size | $(cache_value SHMRING_CACHE_LINE_SIZE) bytes |"
  echo
  if [[ -f "${ROOT}/scripts/bench_notes.md" ]]; then
    cat "${ROOT}/scripts/bench_notes.md"
    echo
  fi
  echo "## Round-trip latency"
  echo
  echo "${PINGPONG}"
  echo
  echo "## Throughput"
  echo
  echo "${THROUGHPUT}"
  echo
  echo "## Run-to-run variation"
  echo
  echo "The same measurement (spsc_ring between two processes, 100000 round trips, one repetition),"
  echo "started afresh 16 times in a row. Median round-trip latency of each run, in nanoseconds:"
  echo
  echo "\`${VARIATION}\`"
  echo
  echo "## Single-operation costs (Google Benchmark)"
  echo
  echo "Run under \`taskset -c ${BENCH_CPU_A},${BENCH_CPU_B}\`, 5 repetitions, aggregates only."
  echo "\`*PushPop\` is one push plus one pop on a single thread; \`SpscStream\` is two threads"
  echo "streaming 8-byte elements, with items counted on the consumer."
  echo
  echo '```'
  echo "${MICRO}"
  echo '```'
} > "${OUT}"
echo "Wrote ${OUT}"
